-- Create the account/profile tables if they do not already exist.

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text UNIQUE NOT NULL,
    password_hash text NOT NULL,
    first_name text,
    middle_name text,
    last_name text,
    suffix text,
    phone text,
    avatar_url text,
    gender text,
    birthdate text,
    address_line1 text,
    address_line2 text,
    city text,
    province text,
    region text,
    postal_code text,
    role text NOT NULL DEFAULT 'customer' CHECK (role IN ('admin', 'customer', 'seller', 'rider')),
    otp_code text,
    is_verified boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sellers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    business_name text,
    category text,
    business_permit text,
    valid_id text,
    address_proof text,
    business_logo text,
    region text,
    province text,
    city text,
    verified boolean NOT NULL DEFAULT false,
    missing_requirements text,
    shop_status text NOT NULL DEFAULT 'pending' CHECK (shop_status IN ('pending', 'active', 'suspended')),
    approved_at timestamptz,
    declined_at timestamptz,
    declined_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    decline_reason text,
    store_name text,
    store_description text,
    store_logo text,
    store_banner text,
    support_phone text,
    support_email text,
    tax_id text,
    payout_method text,
    bank_account_name text,
    bank_account_number text
);

CREATE TABLE IF NOT EXISTS public.riders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    vehicle_type text,
    driver_license text,
    valid_id text,
    vehicle_or_cr text,
    profile_photo text,
    plate_number text,
    verified boolean NOT NULL DEFAULT false,
    rider_status text NOT NULL DEFAULT 'pending' CHECK (rider_status IN ('pending', 'active', 'suspended', 'offline')),
    availability text NOT NULL DEFAULT 'offline' CHECK (availability IN ('available', 'busy', 'offline')),
    current_location text,
    approved_at timestamptz,
    last_active timestamptz,
    suspended_at timestamptz,
    suspended_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    suspension_reason text,
    suspension_type text CHECK (suspension_type IN ('temporary', 'permanent')),
    missing_requirements text,
    declined_at timestamptz,
    declined_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
    decline_reason text,
    phone text,
    avatar_url text,
    address_line1 text,
    city text,
    province text,
    region text,
    status text,
    license_expiry text
);